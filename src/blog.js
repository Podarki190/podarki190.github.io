// Дата — строка ISO, чтобы сравнение было обычным сравнением строк и не
// зависело от часового пояса машины, на которой идёт сборка. Считаем по
// московскому времени, а не по UTC: сборка идёт на чужом сервере, а календарь
// у мастерской свой. Иначе пост, назначенный на 24-е, вылезал бы вечером 23-го.
// Москва — UTC+3 круглый год, перевода часов нет с 2014-го.
const MSK_OFFSET_MS = 3 * 60 * 60 * 1000;

export function publishedPosts(now = new Date()) {
  const stamp = new Date(now.getTime() + MSK_OFFSET_MS).toISOString().slice(0, 10);
  return POSTS.filter(p => p.date <= stamp).sort((a, b) => b.date.localeCompare(a.date));
}

