export const OTHER_THEME = { id: 'prochee', label: 'Разное' };

// Половина названий поэтические («Медовое время»), по ним тему не угадать.
// В описании она названа прямо, но только в первом абзаце: там описан сам
// рисунок. Дальше идёт перечисление «кому подарить» и слова про интерьер,
// кухню и уют — от них любое изделие выглядит как «для дома».
const SUBJECT_CHARS = 300;

export function themeOf(name, description = '') {
  const title = String(name).toLowerCase();
  const subject = `${title} ${String(description).slice(0, SUBJECT_CHARS).toLowerCase()}`;

  for (const theme of THEMES) {
    if (theme.id === 'dom') continue; // слишком общая, разбирается ниже и только по названию
    if (theme.keys.some(key => subject.includes(key))) return theme.id;
  }

  const dom = THEMES.find(t => t.id === 'dom');
  if (dom.keys.some(key => title.includes(key))) return dom.id;

  // «Лучший ортодонт», «Лучшему фтизиатру»: перечислять все специальности
  // бессмысленно, а «лучший кто-то» почти всегда про профессию.
  if (title.includes('лучш')) return 'professii';

  return OTHER_THEME.id;
}
