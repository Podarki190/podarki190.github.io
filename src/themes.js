// Двухслойные распознаются не по тексту, а по артикулу поставщика: у этой
// партии он оканчивается на .jiv. В названии и описании про исполнение
// не сказано ни слова.
export const LAYERED = { id: 'layered', label: 'Двухслойные, ручная работа' };

export const OTHER_THEME = { id: 'prochee', label: 'Разное' };

export const ALL_THEMES = [...SUBJECTS, ...TAGS, LAYERED, OTHER_THEME];

const SUBJECT_CHARS = 300;

const matcher = (keys) => new RegExp(`(?:^|[^а-яёa-z0-9])(?:${keys.join('|')})`, 'i');
const MATCHERS = new Map(ALL_THEMES.filter(t => t.keys).map(t => [t.id, matcher(t.keys)]));

export function themesOf({ name = '', description = '', vendorCode = '' } = {}) {
  const title = String(name).toLowerCase();
  const subject = `${title} ${String(description).slice(0, SUBJECT_CHARS).toLowerCase()}`;

  let found = SUBJECTS.find(theme => MATCHERS.get(theme.id).test(theme.nameOnly ? title : subject));
  if (!found && title.includes('лучш')) {
    // «Лучший фтизиатр», «Лучшему маркшейдеру»: перечислять все специальности
    // бессмысленно, а «лучший кто-то» почти всегда про профессию.
    found = SUBJECTS.find(theme => theme.id === 'professii');
  }

  const themes = [found ? found.id : OTHER_THEME.id];
  for (const tag of TAGS) {
    if (MATCHERS.get(tag.id).test(tag.nameOnly ? title : subject)) themes.push(tag.id);
  }
  if (String(vendorCode).toLowerCase().endsWith('.jiv')) themes.push(LAYERED.id);

  return themes;
}
