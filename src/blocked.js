// Товары, снятые по правам: на сайт не выкладывать, даже если WB их ещё отдаёт.
//
// Зачем список, если карточку уже удалили на WB. Удаление там идёт ДО ТРИДЦАТИ
// ДНЕЙ, и всё это время `content/v2/get/cards/list` продолжает возвращать
// карточку — а сайт собирается именно из этого ответа. Получается месяц, когда
// свой собственный сайт торгует тем, что уже снято по претензии. Здесь этот
// месяц закрывается одной строкой: добавили артикул — со следующей сборки
// страницы нет.
//
// Артикул (nmID) можно взять из адреса карточки на WB или со страницы товара
// на сайте: он в конце slug. Комментарий рядом обязателен — через полгода
// никто не вспомнит, почему товар снят, и кто-нибудь вернёт его обратно.

export const BLOCKED_NM_IDS = new Set([
  // Правообладатель прислал претензию через ООО «Бренд Монитор», 12.08.2026.
  // Товарный знак RU 416159/416155, класс 14 прямо включает часы.
  1261323234, // Часы настенные «КХЛ»

  // Disney. Судятся системно, класс 14 закрыт. Есть и в чёрном списке
  // продавцов — теме «Список запрещённых изображений» ВКонтакте.
  265001652, // Настенные часы Король Лев

  // ПАО «КАМАЗ»: 1831 дело в картотеке, судятся и с ИП
  // (А65-29070/2026 против ИП Парахина, 10.08.2026).
  264805083, // Настенные часы с изображением Камаза
]);

// Снимаем по названию, когда карточек много и перечислять артикулы руками
// дольше, чем описать правило. Сверяется с приведённым к нижнему регистру
// названием, так что достаточно куска слова.
export const BLOCKED_WORDS = [
  // Музыканты сами занялись мерчем — Павел снял эти группы 26.08.2026.
  'люмен', 'lumen',
  'пикник',
  'эпидеми',
  // ПАО «КАМАЗ»: 1831 дело в картотеке, доходят и до ИП.
  // Словом, а не артикулом: карточек может быть больше, чем нашлось.
  'камаз',
];

// Звери сюда НЕ добавлены намеренно. Претензия была от покупателя, а не от
// правообладателя, товар с продажи не снимался. Блокировать — значит убрать
// восемнадцать живых карточек без причины.

export function isBlocked(product) {
  if (BLOCKED_NM_IDS.has(Number(product?.nmId ?? product?.nmID))) return true;
  const name = String(product?.name ?? '').toLowerCase();
  return BLOCKED_WORDS.some(word => name.includes(word));
}
